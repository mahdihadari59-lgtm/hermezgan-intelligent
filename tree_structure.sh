#!/bin/bash
# ============================================================
# اسکریپت نمایش ساختار درختی کامل پروژه
# ============================================================

cd ~/hermezgan-intelligent

echo "=================================================="
echo "🌳 ساختار درختی کامل پروژه هرمزگان هوشمند"
echo "=================================================="
echo "📂 مسیر: $(pwd)"
echo "📅 تاریخ: $(date '+%Y-%m-%d %H:%M:%S')"
echo "=================================================="
echo ""

# ============================================================
# ۱. استفاده از tree (اگر نصب باشد)
# ============================================================
if command -v tree &> /dev/null; then
    echo "📊 ساختار درختی با tree:"
    echo "--------------------------------------------------"
    tree -a -L 4 \
        -I ".git|node_modules|__pycache__|*.pyc|.DS_Store|*.log|*.db|build|dist|coverage|.pytest_cache" \
        --dirsfirst \
        -h \
        --du
else
    echo "⚠️ tree نصب نیست، از find استفاده می‌شود..."
    echo "--------------------------------------------------"
    
    # ساختار با find
    find . -type d \
        -not -path "./.git*" \
        -not -path "./node_modules*" \
        -not -path "./__pycache__*" \
        -not -path "./*.pyc" \
        2>/dev/null | sort | sed 's/[^/]*\//|-- /g;s/|-- /    /g'
fi

echo ""
echo "=================================================="
echo "📊 خلاصه آماری"
echo "=================================================="

# ============================================================
# ۲. آمار تفکیکی
# ============================================================

# تعداد کل فایل‌ها
TOTAL_FILES=$(find . -type f -not -path "./.git/*" -not -path "./node_modules/*" -not -path "./__pycache__/*" 2>/dev/null | wc -l)
TOTAL_DIRS=$(find . -type d -not -path "./.git/*" -not -path "./node_modules/*" -not -path "./__pycache__/*" 2>/dev/null | wc -l)

echo "📄 تعداد کل فایل‌ها: $TOTAL_FILES"
echo "📁 تعداد کل پوشه‌ها: $TOTAL_DIRS"

# ============================================================
# ۳. آمار بر اساس پوشه
# ============================================================
echo ""
echo "📂 آمار پوشه‌های اصلی:"
echo "--------------------------------------------------"

for dir in backend frontend database docs scripts .github; do
    if [ -d "$dir" ]; then
        FILES=$(find "$dir" -type f 2>/dev/null | wc -l)
        SIZE=$(du -sh "$dir" 2>/dev/null | cut -f1)
        echo "  $dir : $FILES فایل, $SIZE"
    fi
done

# ============================================================
# ۴. آمار بر اساس پسوند
# ============================================================
echo ""
echo "📄 آمار بر اساس پسوند:"
echo "--------------------------------------------------"

find . -type f -not -path "./.git/*" -not -path "./node_modules/*" 2>/dev/null | \
    sed 's/.*\.//' | sort | uniq -c | sort -rn | head -15 | \
    while read count ext; do
        if [ -n "$ext" ]; then
            printf "  %-10s : %s\n" "$ext" "$count"
        fi
    done

echo ""
echo "=================================================="
